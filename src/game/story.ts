/** 当前赛季剧情：与官方赛季同步（S1~S11）；超出已知档期按月份循环全幕 */
export function currentSeasonStory(d = new Date()): SeasonStory {
  const s = currentOfficialSeason(d)
  if (s) {
    const arc = STORY_ARCS.find(a => a.num === s.num)
    if (arc) return arc
  }
  const idx = (d.getFullYear() * 12 + d.getMonth()) % STORY_ARCS.length
  return STORY_ARCS[idx]
}

/** 上一赛季剧情（用于「上季回顾」衔接） */
export function prevSeasonStory(d = new Date()): SeasonStory {
  const cur = currentSeasonStory(d)
  const i = STORY_ARCS.indexOf(cur)
  return STORY_ARCS[(i - 1 + STORY_ARCS.length) % STORY_ARCS.length]
}

